const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { PGlite } = require('@electric-sql/pglite');
(async () => {
  const db = new PGlite();
  const root = path.resolve(__dirname, '../../..');
  const read = file => fs.readFileSync(path.join(root,file),'utf8').replace('create extension if not exists pgcrypto;','');
  const one = async (sql,args=[]) => (await db.query(sql,args)).rows[0];
  await db.exec(`create role anon; create role authenticated; create role service_role;
    create schema auth; create table auth.users(id uuid primary key,email text);
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    create function auth.email() returns text language sql stable as $$ select nullif(current_setting('request.jwt.claim.email',true),'') $$;
    create function auth.jwt() returns jsonb language sql stable as $$ select jsonb_build_object('email',auth.email()) $$;
    grant usage on schema auth to anon,authenticated;`);
  for (const file of ['supabase-schema.sql','supabase-admin-workflow.sql','supabase-database-integrity.sql','supabase-test-mode.sql','supabase-qq-participation.sql','supabase-account-moderation.sql','supabase-song-catalog.sql']) await db.exec(read(file));
  await db.exec(read('supabase-song-catalog.sql'));
  const admin='11111111-1111-4111-8111-111111111111', tester='22222222-2222-4222-8222-222222222222';
  await db.query("insert into auth.users values($1,'admin@example.invalid'),($2,'tester@example.invalid')",[admin,tester]);
  await db.query("insert into admin_users(email,user_id) values('admin@example.invalid',$1)",[admin]);
  const role = async (name, id='') => {
    await db.exec('reset role');
    await db.query("select set_config('request.jwt.claim.sub',$1,false),set_config('request.jwt.claim.email',$2,false)",[id,id===admin?'admin@example.invalid':'']);
    await db.exec('set role '+name);
  };
  await db.exec('update security_settings set submission_cookie_per_minute=100');
  await role('authenticated',admin);
  const period=(await one("select admin_create_playlist_period('曲库测试',now()-interval '1 day',now()+interval '1 day') id")).id;
  const create=async(title,available=true,active=true)=>(await one("select admin_upsert_song_catalog(null,$1,'歌手','studio:file',200,$2,$3,'internal note') id",[title,available,active])).id;
  const c1=await create('一'),c2=await create('二'),missing=await create('无音源',false),disabled=await create('停用',true,false);
  await assert.rejects(db.query("select admin_upsert_song_catalog(null,'空音源','歌手','',200,true,true,'')"),/音源/);
  assert.equal((await db.query('select * from song_catalog')).rows.length,4,'admin table read granted');
  const policy=async(enabled,ids,start=null,end=null,version=0)=>db.query('select admin_set_period_catalog_policy($1,$2,$3,$4,$5,$6)',[period,enabled,ids,start,end,version]);
  await policy(true,[c1]);
  await assert.rejects(policy(false,[],null,null,0),/其他管理员/);
  assert.deepEqual((await one('select * from period_catalog_policies')).allowed_catalog_ids,[c1]);
  await role('anon');
  await assert.rejects(db.query('select source_url from song_catalog'),/permission denied/);
  let list=(await db.query('select * from get_song_catalog($1)',[period])).rows;
  assert.deepEqual(list.map(r=>r.id),[c1]);assert.equal(list[0].source_url,undefined);assert.equal(list[0].notes,'');
  assert.equal((await db.query('select * from get_song_catalog(null)')).rows.length,0);
  for (const name of ['anon','authenticated','service_role']) {
    await role(name);
    await assert.rejects(db.query('select * from submit_song_from_catalog($1,$2,$3)',[c1,period,'forged-cookie']),/permission denied/);
  }
  const submit=async(catalog,openid='QQ_A',testId=null)=> (await one("select qq_participate('123',$1,'同学','','submit',$2,$3,'伪造歌名','伪造歌手',null,null,$4) result",[openid,period,catalog,testId])).result;
  await role('anon');await assert.rejects(submit(c1),/permission denied/);
  await role('service_role');
  assert((await one('select qq_catalog_health() result')).result.ok);
  for (const id of [null,missing,disabled,c2]) assert.match((await submit(id)).error_message,/音源|范围/);
  const added=await submit(c1);assert(added.id,JSON.stringify(added));assert.equal(added.title,'一');
  assert.match((await submit(c1)).error_message,/已有/);
  await db.exec('reset role');
  assert.equal((await one('select catalog_id from songs where id=$1',[added.id])).catalog_id,c1);
  const account=(await one("select id from qq_accounts where openid='QQ_A'")).id;
  assert.equal((await one('select count(*)::int n from api_request_attempts where cookie_hash=md5($1)',[account])).n,6,'failures retain counters');
  await role('authenticated',admin);
  await policy(true,[c1],'2090-01-01','2091-01-01',1);
  await role('anon');assert.equal((await db.query('select * from get_song_catalog($1)',[period])).rows.length,2,'future schedule inactive');
  await role('authenticated',admin);await policy(true,[],'2000-01-01','2001-01-01',2);
  await role('service_role');const second=await submit(c2,'QQ_B');assert(second.id,'expired schedule permits posting');
  await role('authenticated',admin);await policy(true,[],null,null,3);
  await role('service_role');assert.match((await submit(c2,'QQ_C')).error_message,/范围/);
  await role('authenticated',admin);await policy(false,[],null,null,4);
  await db.query("select admin_moderate_account($1,'ban','测试封禁',24,0)",[account]);
  await role('service_role');assert.equal((await submit(c1)).error,'account_banned');
  await role('authenticated',admin);
  await db.query("select admin_set_test_account('tester@example.invalid',true)");
  await db.query('select admin_set_period_test_mode($1,true,false)',[period]);
  await role('anon');assert.equal((await db.query('select * from get_song_catalog($1)',[period])).rows.length,0);
  await role('service_role');assert.equal((await submit(c1,'QQ_D')).error,'test_login_required');
  await role('authenticated',tester);assert.equal((await db.query('select * from get_song_catalog($1)',[period])).rows.length,2);
  await assert.rejects(create('越权'),/Admin permission/);
  await assert.rejects(policy(false,[],null,null,5),/Admin permission/);
  await role('authenticated',admin);const c3=await create('测试歌');
  await role('service_role');assert((await submit(c3,'QQ_D',tester)).id);
  await db.exec('reset role');await db.exec(read('supabase-song-catalog.sql'));
  assert.equal((await one('select count(*)::int n from songs')).n,3,'repeat migration preserves songs');
  assert.equal((await one('select count(*)::int n from song_catalog')).n,5);
  // An old migration overwrite must fail release readiness, not silently bypass catalog checks.
  await db.exec(read('supabase-account-moderation.sql'));
  assert.equal((await one('select qq_catalog_health() result')).result.ok,false);
  await db.exec(read('supabase-song-catalog.sql'));
  assert.equal((await one('select qq_catalog_health() result')).result.ok,true);
  await db.close();
  console.log('PASS catalog: repeated migration, privileges, source privacy, forged/legacy bypass, availability, scheduled whitelist, stale saves, failures counted, canonical titles, QQ bans/test permissions and health overwrite checks');
})().catch(e=>{console.error(e);process.exit(1);});
